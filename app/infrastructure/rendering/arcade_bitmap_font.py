@lru_cache(maxsize=4)
def load_arcade_pixel_font() -> ImageFont.ImageFont:
    """Compile and cache the `cp1252` 11-row arcade pixel bitmap font in memory."""
    glyph_map = _build_cp1252_glyph_map()
    bdf: List[str] = [
        "STARTFONT 2.1",
        "FONT -ArcadeMatrix-Pixel-Medium-R-Normal--11-110-75-75-P-60-ISO8859-1",
        "SIZE 11 75 75",
        "FONTBOUNDINGBOX 7 11 0 -2",
        "STARTPROPERTIES 2",
        "FONT_ASCENT 9",
        "FONT_DESCENT 2",
        "ENDPROPERTIES",
        f"CHARS {len(glyph_map)}",
    ]

    for code in sorted(glyph_map):
        rows = glyph_map[code]
        cell_w = len(rows[0])
        dwidth = 3 if code in (0x20, 0xA0) else (cell_w + 1)
        bdf.extend(
            [
                f"STARTCHAR C{code:02X}",
                f"ENCODING {code}",
                f"SWIDTH {dwidth * 90} 0",
                f"DWIDTH {dwidth} 0",
                f"BBX {cell_w} 11 0 -2",
                "BITMAP",
            ]
        )
        for row in rows:
            byte_val = 0
            for idx, px in enumerate(row[:8]):
                if px == "#":
                    byte_val |= 1 << (7 - idx)
            bdf.append(f"{byte_val:02X}")
        bdf.append("ENDCHAR")
    bdf.append("ENDFONT")

    bf = BdfFontFile.BdfFontFile(io.BytesIO(("\n".join(bdf) + "\n").encode("ascii")))
    bf.compile()
    if bf.bitmap is None:
        return ImageFont.load_default()

    pil_header = (
        b"PILfont\n"
        + f";;;;;;{bf.ysize};\n".encode("ascii")
        + b"DATA\n"
        + bf._encode_metrics()
    )
    if hasattr(ImageFont.ImageFont, "_load_pilfont_data"):
        font_obj = ImageFont.ImageFont()
        font_obj._load_pilfont_data(io.BytesIO(pil_header), bf.bitmap)
        return font_obj

    with tempfile.TemporaryDirectory(prefix="dmd_pilfont_") as tmp_dir:
        pil_path = os.path.join(tmp_dir, "arcade_pixel.pil")
        bf.save(pil_path)
        return ImageFont.load(pil_path)


def can_encode_cp1252(text: str) -> bool:
    """Return `True` when every character in `text` fits in our `cp1252` arcade pixel font."""
    if not text:
        return True
    try:
        text.encode("cp1252")
        return True
    except UnicodeEncodeError:
        return False


def encode_for_arcade_bitmap_font(text: str) -> str:
    """Map Unicode `cp1252` characters (`é`, `É`, `ç`, `œ`, `Œ`, `€`, `«`, `»`) to 1-byte glyph indices."""
    if not text:
        return ""
    return text.encode("cp1252", "replace").decode("latin-1")


