# Dotless `i` stem (`4` cols wide so circumflex/diaeresis accents fit cleanly above `î` / `ï`)
_DOTLESS_I: List[str] = ["....", "....", "....", "....", ".##.", "..#.", "..#.", "..#.", "####", "....", "...."]
_WIDE_CAP_I: List[str] = [".....", ".....", ".....", ".###.", "..#..", "..#..", "..#..", "..#..", ".###.", ".....", "....."]


def _overlay_top_accent(base: List[str], kind: str, is_upper: bool) -> List[str]:
    w = max(4, len(base[0]))
    rows = [r.center(w, ".") if len(r) < w else r for r in base]
    r0_idx = 0 if is_upper else 1
    r1_idx = 1 if is_upper else 2
    mid = w // 2

    def _put(cols: Tuple[int, ...]) -> str:
        buf = ["."] * w
        for c in cols:
            if 0 <= c < w:
                buf[c] = "#"
        return "".join(buf)

    if kind == "acute":
        rows[r0_idx] = _put((min(w - 1, mid + 1),))
        rows[r1_idx] = _put((mid,))
    elif kind == "grave":
        rows[r0_idx] = _put((max(0, mid - 1),))
        rows[r1_idx] = _put((mid,))
    elif kind == "circ":
        rows[r0_idx] = _put((mid,))
        rows[r1_idx] = _put((max(0, mid - 1), min(w - 1, mid + 1)))
    elif kind == "umlaut":
        rows[r1_idx] = _put((max(0, mid - 1), min(w - 1, mid + 1)))
    elif kind == "tilde":
        rows[r0_idx] = _put((max(0, mid - 1), min(w - 1, mid + 1)))
        rows[r1_idx] = _put((max(0, mid - 2), mid))
    elif kind == "ring":
        rows[r0_idx] = _put((mid,))
        rows[r1_idx] = _put((max(0, mid - 1), min(w - 1, mid + 1)))
    return rows


def _overlay_cedilla(base: List[str]) -> List[str]:
    w = len(base[0])
    rows = list(base)
    mid = w // 2
    r9 = ["."] * w
    r10 = ["."] * w
    r9[mid] = "#"
    r10[max(0, mid - 1)] = "#"
    r10[mid] = "#"
    rows[9] = "".join(r9)
    rows[10] = "".join(r10)
    return rows


