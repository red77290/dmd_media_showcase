def pick_localized_text(translations: Dict[str, str], lang: str) -> str:
    """Resolve localized text with cascade: requested `lang` -> `en` -> `fr` -> first available."""
    short = (lang or "fr").split("-")[0].lower()
    if short in translations and translations[short]:
        return translations[short]
    if "en" in translations and translations["en"]:
        return translations["en"]
    if "fr" in translations and translations["fr"]:
        return translations["fr"]
    return next(iter(translations.values()), "")


